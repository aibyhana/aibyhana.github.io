PX.sprout_b = PX.sprout.map((r, i) => i === 0 ? ".###...##" : r);
PX.blades_b = PX.blades.map((r, i) => i === 0 ? ".....#..." : i === 1 ? ".....#..#" : r);
const TEMPO = { sprout: 2.3, blades: 2.9, bot: 0.34, star: 4.4, bigstar: 5.8 };
export function pathOf(rows) {
  const w = rows[0].length;
  let d = "";
  rows.forEach((r, y) => {
    let x = 0;
    while (x < w) {
      if (r[x] !== "#") { x++; continue; }
      const x0 = x; while (x < w && r[x] === "#") x++;
      d += "M" + x0 + " " + y + "h" + (x - x0) + "v1h-" + (x - x0) + "z";
    }
  });
  return d;
}
export function px(name, size) {
  const rows = PX[name], w = rows[0].length, h = rows.length, two = PX[name + "_b"];
  const moving = two ? ' style="--t:' + (TEMPO[name] || 1.6) + "s;--d:-" + (Math.random() * 3).toFixed(2) + 's"' : "";
  return '<svg class="px' + (two ? " ani" : "") + '" viewBox="0 0 ' + w + " " + h + '" width="' + w * size + '" height="' + h * size + '" aria-hidden="true"' + moving + ">" +
    (two ? '<path class="f1" d="' + pathOf(rows) + '"/><path class="f2" d="' + pathOf(two) + '"/>' : '<path d="' + pathOf(rows) + '"/>') + "</svg>";
}
